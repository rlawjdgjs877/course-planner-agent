import assert from 'node:assert/strict';
import { defaultPlanning, restorePlanning, validatePlanning, parseMeetingTimes, checkSectionConflicts } from '../app/lib/planning.ts';
const section=(id,code,time)=>({id,code,time,name:id});
const a=section('A-001','A','월 09:00 ~ 10:30');
assert.equal(validatePlanning(defaultPlanning).length,0);
assert(validatePlanning({...defaultPlanning,min_credits:20}).length);
assert(validatePlanning({...defaultPlanning,must_include:['COMP0204-001'],exclude:['COMP0204']}).length);
assert.equal(checkSectionConflicts([a,section('B-001','B','월 10:30 ~ 12:00')]).ok,true);
assert.equal(checkSectionConflicts([a,section('B-001','B','월 10:00 ~ 12:00')]).conflicts[0].start,600);
assert.equal(checkSectionConflicts([a,section('A-002','A','화 09:00 ~ 10:00')]).duplicate_courses.length,1);
assert.equal(checkSectionConflicts([a,section('B-001','B','')]).ok,false);
assert.equal(checkSectionConflicts([{...a,inconsistent:true}]).unresolved.length,1);
assert.equal(parseMeetingTimes('월 09:00 ~ 10:00, 알수없음'),null);
assert.equal(parseMeetingTimes('화 09:00 ~ 10:30,목 10:30 ~ 12:00').length,2);
assert.equal(parseMeetingTimes('토 09:00 ~ 10:30,토 10:30 ~ 12:00').length,2);
assert.equal(parseMeetingTimes('월 24:00 ~ 25:00'),null);
const migrated=restorePlanning(null,12,'금');
assert.equal(migrated.min_credits,12);assert.equal(migrated.target_credits,12);
assert.deepEqual(migrated.free_days,[]);assert.equal(migrated.avoid_times[0].day,'금');
assert.equal(restorePlanning({...defaultPlanning,base_candidate_id:'tt_001'}).base_candidate_id,null);
assert.deepEqual(restorePlanning({...defaultPlanning,grade:'A+',password:'test'}),defaultPlanning);
assert.deepEqual(restorePlanning({...defaultPlanning,blocked_times:[{day:'월',start:'12:00',end:'09:00'}]}).blocked_times,[]);
console.log('PASS: meeting parsing, adjacent vs overlapping times, duplicate sections, unresolved and inconsistent times, invalid constraints, legacy preference migration and session ID isolation.');
